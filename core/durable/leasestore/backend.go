// Package leasestore implements durable.Store and session.Store on top of
// leases without containing any SQL or driver dependency. The in-process
// gates, lease tokens, renewal loop, shutdown and compensation live here;
// reads and writes go through a Backend the caller implements with any
// database, driver or ORM and its own tables.
package leasestore

import (
	"context"
	"fmt"
	"time"

	agentErrors "github.com/kart-io/goagent/errors"
)

// Lease identifies one holding. NS is the namespace (empty for the root; scopes
// and sessions each have a prefix), ID is the lock name inside it and Token is
// generated by this package on every acquisition. A backend decides "still
// held by this holder" only by (NS, ID, Token) being equal.
type Lease struct {
	NS, ID, Token string
}

// SnapshotWrite is one write of SaveSnapshots. Data is the serialized snapshot
// and is stored and returned unchanged.
type SnapshotWrite struct {
	Lease Lease
	Data  []byte
}

// EventBatch is one append to one session. Seqs, Types and Data have the same
// length and Seqs increases by one from Expected+1; all three empty means
// compare only. Fences are the leases of the durable snapshots in the batch
// and must be verified in the same transaction.
type EventBatch struct {
	SessionID string
	Expected  int64
	Seqs      []int64
	Types     []string
	Data      [][]byte
	Fences    []Lease
}

// Backend is the storage port for leases and snapshots. Unless stated
// otherwise each method is one atomic operation and a nil return means the
// change is durably committed.
//
// Time is always computed by the backend's own clock (methods take durations,
// not instants), and every instance of one backend must share that clock,
// normally the database server's.
//
// Errors: a removed scope returns errors.ErrScopeRemoved, a token that no
// longer matches returns errors.ErrLeaseLost, anything else is returned as is.
type Backend interface {
	// AcquireLease writes l and returns true when (NS, ID) has no lease or an
	// expired one, and returns false while another holder has it. It returns
	// ErrScopeRemoved when the scope of NS is removed and must exclude
	// RemoveScope: it cannot succeed after the tombstone is committed. Once a
	// write was attempted and its outcome is unknown, wrap the error with
	// Uncertain; this package then compensates with ReleaseLease.
	AcquireLease(ctx context.Context, l Lease, owner string, ttl time.Duration) (bool, error)

	// ReleaseLease deletes the lease whose token matches and succeeds when it
	// does not match or does not exist. It must be serialized with
	// AcquireLease on the same (NS, ID): it waits for an unfinished acquire
	// and cannot miss a lease with the same token committed afterwards. Scope
	// tombstones do not affect it.
	ReleaseLease(ctx context.Context, l Lease) error

	// RenewLeases extends the leases whose token still matches to now+ttl and
	// ignores the rest. The batch need not be atomic.
	RenewLeases(ctx context.Context, leases []Lease, ttl time.Duration) error

	// DeleteExpiredLeases deletes leases expired for longer than grace.
	DeleteExpiredLeases(ctx context.Context, grace time.Duration) error

	// LoadSnapshot reads a snapshot; found is false when it does not exist. A
	// removed scope returns ErrScopeRemoved.
	LoadSnapshot(ctx context.Context, ns, id string) (data []byte, found bool, err error)

	// SaveSnapshots writes all snapshots of one NS in one transaction. It
	// verifies every token (expiry is not checked, a takeover always rewrites
	// the token); any mismatch rolls everything back with ErrLeaseLost. The
	// verified leases are extended to now+ttl. It must exclude RemoveScope.
	// writes is sorted by ID.
	SaveSnapshots(ctx context.Context, ns string, writes []SnapshotWrite, ttl time.Duration) error

	// RemoveScope commits a tombstone, then deletes the snapshots and leases
	// of NS; an existing tombstone keeps its time. Once the tombstone is
	// committed NS can no longer be read or written; the deletion may run in
	// batches and calling again continues an interrupted one.
	RemoveScope(ctx context.Context, ns string) error

	// PruneScopes reclaims scopes whose tombstone is older than now-olderThan:
	// it deletes leftover data and the tombstone.
	PruneScopes(ctx context.Context, olderThan time.Duration) error
}

// SessionBackend is the storage port for session logs and shares the leases
// of Backend.
//
// Errors: a sequence mismatch returns Conflict(id, expected, current), a
// missing session errors.ErrSessionNotFound, an existing target
// errors.ErrSessionExists and a Fences mismatch errors.ErrLeaseLost.
type SessionBackend interface {
	// LastSeq returns the last sequence of a session, 0 when it does not exist.
	LastSeq(ctx context.Context, id string) (int64, error)

	// AppendEvents applies all batches in one transaction; any failure rolls
	// everything back. For each batch it verifies Fences (as SaveSnapshots
	// does, extending them to now+ttl), then compares the session's current
	// sequence with Expected and only when equal writes the events and
	// advances the sequence to the last Seq. The comparison must be
	// serialized with concurrent appends, forks and deletes and hold until
	// commit; an empty batch only compares and must not leave a session row.
	// batches is sorted by SessionID and Fences by ID.
	AppendEvents(ctx context.Context, batches []EventBatch, ttl time.Duration) error

	// ReadEvents returns the events with seq > after in ascending order. A
	// missing session returns ErrSessionNotFound; a session with nothing newer
	// returns an empty slice.
	ReadEvents(ctx context.Context, id string, after int64) ([][]byte, error)

	// ListSessions returns all session IDs in byte order.
	ListSessions(ctx context.Context) ([]string, error)

	// ForkSession copies the events of src with seq <= upTo (upTo <= 0 means
	// all) into a new session dst. The copy is a whole prefix: a concurrent
	// append to src is either entirely included or entirely excluded.
	ForkSession(ctx context.Context, src, dst string, upTo int64) error

	// DeleteSession deletes a session and all its events and succeeds when the
	// session does not exist; it must be serialized with concurrent appends
	// and forks.
	DeleteSession(ctx context.Context, id string) error
}

// Conflict is the error a SessionBackend returns when a session's current
// sequence differs from the expected one; it wraps errors.ErrSessionConflict.
func Conflict(id string, expected, current int64) error {
	return fmt.Errorf("%w：会话 %q 期望序号 %d，当前 %d", agentErrors.ErrSessionConflict, id, expected, current)
}

// uncertain 标记"已尝试写入、结果不确定"的错误。
type uncertain struct{ err error }

func (u uncertain) Error() string { return u.err.Error() }
func (u uncertain) Unwrap() error { return u.err }

// Uncertain wraps an error AcquireLease returns after attempting a write; nil
// is returned unchanged.
func Uncertain(err error) error {
	if err == nil {
		return nil
	}
	return uncertain{err}
}
